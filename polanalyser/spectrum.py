def spectrum_to_color(values: np.ndarray, wvls: np.ndarray) -> np.ndarray:
    """Converts a spectrum to color.

    Parameters
    ----------
    values : np.ndarray, (..., N)
        Spectrum values.
    wvls : np.ndarray, (N,)
        Wavelengths of the spectrum.

    Returns
    -------
    np.ndarray, (..., 3)
        Color values in BGR order.
    """
    if values.shape[-1] != wvls.shape[0]:
        raise ValueError(f"The number of wavelengths should match the last dimension of the values. Got {values.shape[-1]} and {wvls.shape[0]}.")

    # Load CIE 1931 2deg data
    ref_wvls = cmf[:, 0]
    ref_xyz = cmf[:, 1:]

    # Interpolate CIE 1931 2deg observer data to match the input wavelengths
    interpolated_xyz = np.zeros((len(wvls), 3))
    for i in range(3):
        interpolated_xyz[:, i] = np.interp(wvls, ref_wvls, ref_xyz[:, i])

    # Spectrum to XYZ
    xyz = np.dot(values, interpolated_xyz)

    # XYZ to sRGB
    matrix = np.array([[3.2406, -1.5372, -0.4986], [-0.9689, 1.8758, 0.0415], [0.0557, -0.2040, 1.0570]])
    rgb = np.dot(xyz, matrix.T)
    rgb = np.clip(rgb, 0, 1)

    # RGB to BGR (for OpenCV)
    bgr = rgb[..., ::-1]

    return bgr
